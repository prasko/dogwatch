#!/usr/bin/env python3
"""Deploy shared workflow skills and role definitions to Codex and Claude Code."""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
LEGACY_MARKER = "# Generated by agentic-setup; edit source roles and redeploy.\n"
PREVIOUS_MARKER = "# Generated by agentic-setup; edit repository sources and redeploy.\n"
MARKER = "# Generated by dogwatch; edit repository sources and redeploy.\n"
# Claude agent files must start with YAML frontmatter, so the marker is its first line.
CLAUDE_MARKER = "---\n" + MARKER
ROLES = ("lead", "scoper", "architect", "developer", "tester", "validator", "reviewer")
SKILLS = ("scope", "design", "implement", "test", "validate", "research", "setup-feedback",
          "write-doc")
ROLE_SKILLS = {"scoper": ("scope",), "architect": ("design",),
               "developer": ("implement", "test", "validate"),
               "tester": ("test",), "validator": ("validate",)}
RETIRED = {"codex": ("agents/researcher.toml", "agentic-researcher.config.toml"),
           "claude": ("agents/agentic-researcher.md",)}
TARGETS = ("codex", "claude")
TIERS = ("fast", "standard", "deep", "special")
EFFORTS = ("low", "medium", "high", "xhigh", "max")
EFFORT_KEY = {"codex": "model_reasoning_effort", "claude": "effort"}
CONTEXT_KEYS = {"model_context_window", "model_auto_compact_token_limit"}
TIER_KEYS = {target: {"model", key} for target, key in EFFORT_KEY.items()}
TIER_KEYS["codex"] |= CONTEXT_KEYS
ROLE_KEYS = {"codex": TIER_KEYS["codex"], "claude": TIER_KEYS["claude"] | {"tools"}}
CLAUDE_AGENT_NOTE = (
    "Dogwatch role. Use only when another Dogwatch role or the user explicitly "
    "assigns this role. "
)


def _check_table(where, table, names, allowed):
    """Validate table names, allowed keys and string/token-count value types."""
    if set(table) != set(names):
        raise ValueError(f"{where} must define exactly: {', '.join(names)}")
    for name, settings in table.items():
        if not isinstance(settings, dict) or set(settings) - allowed:
            raise ValueError(f"Unsupported settings for {name} in {where}")
        for key, value in settings.items():
            if key in CONTEXT_KEYS:
                if type(value) is not int or value <= 0:
                    raise ValueError(f"{key} for {name} in {where} must be a positive integer")
            elif not isinstance(value, str) or not value:
                raise ValueError(f"{key} for {name} in {where} must be a nonempty string")
    return table


def _load_runtime(root, target):
    """Return {role: settings}, resolving each role's tier and applying role overrides."""
    shared = _check_table("roles/roles.toml", tomllib.loads((root / "roles/roles.toml").read_text()),
                          ROLES, {"description", "tier"})
    where = f"{target}/roles.toml"
    config = tomllib.loads((root / where).read_text())
    if set(config) != {"tiers", "roles"}:
        raise ValueError(f"{where} must contain only [tiers.*] and [roles.*] tables")
    tiers = _check_table(f"{where} [tiers]", config["tiers"], TIERS, TIER_KEYS[target])
    roles = _check_table(f"{where} [roles]", config["roles"], ROLES, ROLE_KEYS[target])
    resolved = {}
    for role in ROLES:
        description, tier = shared[role].get("description"), shared[role].get("tier")
        if not description or tier not in TIERS:
            raise ValueError(f"roles/roles.toml must give {role} a description and a tier "
                             f"({', '.join(TIERS)})")
        settings = {**tiers[tier], **roles[role]}
        effort = settings.get(EFFORT_KEY[target])
        if effort is not None and effort not in EFFORTS:
            raise ValueError(f"Unsupported effort {effort!r} for {role} in {where}")
        resolved[role] = {"description": description, "tier": tier, **settings}
    for tier, settings in tiers.items():
        if settings.get(EFFORT_KEY[target], "low") not in EFFORTS:
            raise ValueError(f"Unsupported effort for tier {tier} in {where}")
    for settings in (*tiers.values(), *resolved.values()):
        window = settings.get("model_context_window")
        compact = settings.get("model_auto_compact_token_limit")
        if window is not None and compact is not None and compact >= window:
            raise ValueError(f"Compaction threshold must be below the context window in {where}")
    return resolved, tiers


def _tier_notes(target, tiers, resolved):
    key = EFFORT_KEY[target]

    def cells(settings):
        return (f"{settings.get('model', 'session default')} | "
                f"{settings.get(key, 'session default')}")

    tier_rows = "".join(f"| `{tier}` | {cells(settings)} |\n" for tier, settings in tiers.items())
    role_rows = "".join(f"| {role} | `{settings['tier']}` | {cells(settings)} |\n"
                        for role, settings in resolved.items())
    return ("\n\n### Model tiers\n\n| Tier | Model | Effort |\n| --- | --- | --- |\n"
            + tier_rows
            + "\n### Role defaults\n\nIncludes per-role overrides; an assignment's stated tier "
            "replaces them.\n\n| Role | Tier | Model | Effort |\n| --- | --- | --- | --- |\n"
            + role_rows)


def _load_skills(root):
    """Read portable skills. Source frontmatter uses JSON-quoted YAML scalars."""
    skills = {}
    for skill in SKILLS:
        source = root / f"skills/dogwatch-{skill}/SKILL.md"
        content = source.read_text()
        if not content.startswith("---\n"):
            raise ValueError(f"Missing frontmatter: {source}")
        frontmatter, body = content[4:].split("\n---\n", 1)
        fields = {}
        for line in frontmatter.splitlines():
            key, value = line.split(":", 1)
            if key in fields:
                raise ValueError(f"Duplicate skill field: {source}: {key}")
            fields[key] = json.loads(value.strip())
        if (set(fields) != {"name", "description"}
                or fields["name"] != f"dogwatch-{skill}"
                or not isinstance(fields["description"], str)
                or not fields["description"].strip() or not body.strip()):
            raise ValueError(f"Invalid skill metadata or empty body: {source}")
        skills[skill] = (content, body.strip())
    return skills


def _instructions(root, role, target, tiers, resolved, skills):
    parts = [root / "roles/common.md", root / f"roles/{role}.md", root / f"{target}/notes.md"]
    texts = [path.read_text().strip() for path in parts]
    if not all(texts):
        raise ValueError(f"Empty instructions for {role} ({target})")
    texts[2:2] = [skills[skill][1] for skill in ROLE_SKILLS.get(role, ())]
    if role == "lead":
        contracts = "\n".join(f"- **{name.title()}:** {settings['description']}"
                              for name, settings in resolved.items() if name != "lead")
        texts.insert(-1, "## Delegated role contracts\n\n" + contracts)
    return "\n\n".join(texts) + _tier_notes(target, tiers, resolved)


def _toml(values):
    # JSON strings with literal Unicode are also valid TOML basic strings.
    content = MARKER + "".join(
        f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in values.items())
    assert tomllib.loads(content) == values
    return content


def render(root=ROOT, targets=TARGETS):
    """Return {target: {relative path: content}}."""
    outputs = {}
    skills = _load_skills(root)
    for target in targets:
        resolved, tiers = _load_runtime(root, target)
        files = outputs[target] = {}
        for role in ROLES:
            runtime = dict(resolved[role])
            description = runtime.pop("description")
            del runtime["tier"]
            instructions = _instructions(root, role, target, tiers, resolved, skills)
            if target == "codex":
                # Custom-agent model settings override spawn-time values in Codex, so
                # subagents leave them to the caller; interactive profiles pin them.
                files[f"agents/dogwatch-{role}.toml"] = _toml(
                    {"name": f"dogwatch-{role}", "description": description,
                     "developer_instructions": instructions})
                files[f"dogwatch-{role}.config.toml"] = _toml(
                    {**runtime, "developer_instructions": instructions})
            else:
                # JSON strings are valid YAML double-quoted scalars.
                frontmatter = {"name": f"dogwatch-{role}",
                               "description": CLAUDE_AGENT_NOTE + description, **runtime}
                files[f"agents/dogwatch-{role}.md"] = (
                    CLAUDE_MARKER
                    + "".join(f"{key}: {json.dumps(value, ensure_ascii=False)}\n"
                              for key, value in frontmatter.items())
                    + "---\n\n" + instructions)
        for skill, (content, _) in skills.items():
            files[f"skills/dogwatch-{skill}/SKILL.md"] = "---\n" + MARKER + content[4:]
    return outputs


def is_managed(text):
    return any(text.startswith(prefix + marker)
               for prefix in ("", "---\n") for marker in (MARKER, PREVIOUS_MARKER, LEGACY_MARKER))


def deploy(outputs, *, retired=(), dry_run=False, check=False, replace=False, uninstall=False):
    """Preflight all collisions; back up changed files and replace each atomically.

    `outputs` maps absolute destination paths to content.
    """
    changes = []
    for path, content in outputs.items():
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Refusing symlink destination: {path}")
        old = path.read_text() if path.exists() else None
        if old == content:
            continue
        if not check and old is not None and not is_managed(old) and not replace:
            raise ValueError(f"Unmanaged file: {path}. Review it, then use --replace to back it up.")
        changes.append((path, content, old))

    retirements = []
    # Custom provider homes may share skill paths.
    for path in dict.fromkeys(retired):
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Refusing symlink destination: {path}")
        if path.exists():
            if is_managed(path.read_text()):
                retirements.append(path)
            else:
                print(f"Preserving unmanaged file: {path}")

    if check:
        for path, _, _ in changes:
            print(f"OUT OF DATE {path}")
        for path in retirements:
            print(f"RETIRED {path}")
        if not changes and not retirements:
            print("Installed files match source.")
        return 1 if changes or retirements else 0

    for path, content, old in changes:
        print(f"{'Would write' if dry_run else 'Write'} {path}")
        if dry_run:
            if old is not None:
                print("  Would back up existing file.")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if old is not None:
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
            backup = path.with_name(f"{path.name}.bak-{stamp}")
            # Preserve exact bytes in backups, including original line endings.
            with backup.open("xb") as handle:
                handle.write(path.read_bytes())
            print(f"  Backup {backup}")
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                             delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(content)
            temporary.replace(path)
        finally:
            if temporary is not None and temporary.exists():
                temporary.unlink()
    for path in retirements:
        action = "Remove" if uninstall else "Retire"
        print(f"{'Would ' + action.lower() if dry_run else action} {path}")
        if not dry_run:
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
            backup = path.with_name(f"{path.name}.bak-{stamp}")
            with backup.open("xb") as handle:
                handle.write(path.read_bytes())
            path.unlink()
            print(f"  Backup {backup}")
    if not changes and not retirements:
        print("Already up to date.")
    return 0


def resolve(rendered, homes):
    """Combine rendered relative paths with each target's home directory."""
    return {homes[target] / relative: content
            for target, files in rendered.items() for relative, content in files.items()}


def component_paths(target, component="all", *, legacy=False):
    """Known package files only; never glob user agent or skill directories."""
    prefix = "agentic" if legacy else "dogwatch"
    paths = []
    if component != "skills":
        for role in ROLES:
            if target == "codex":
                paths.extend((f"agents/{role if legacy else 'dogwatch-' + role}.toml",
                              f"{prefix}-{role}.config.toml"))
            else:
                paths.append(f"agents/{prefix}-{role}.md")
    if component != "roles":
        paths.extend(f"skills/{prefix}-{skill}/SKILL.md" for skill in SKILLS)
    return tuple(paths)


def retired_paths(homes, targets=TARGETS, component="all"):
    paths = []
    for target in targets:
        relative = component_paths(target, component, legacy=True)
        if component != "skills":
            relative = RETIRED[target] + relative
        paths.extend(homes[target] / path for path in relative)
    return tuple(paths)


def uninstall_paths(homes, targets=TARGETS, component="all"):
    return tuple(homes[target] / relative for target in targets
                 for relative in component_paths(target, component)) + retired_paths(homes, targets, component)


def warn_skill_dependencies(homes, targets):
    for target in targets:
        paths = [homes[target] / relative
                 for legacy in (False, True)
                 for relative in component_paths(target, "roles", legacy=legacy)]
        if any(path.is_file() and not path.is_symlink() and is_managed(path.read_text())
               for path in paths):
            print(f"Warning: installed {target} Dogwatch roles still use these skills; "
                  "remove the roles too or redeploy the skills before using them.", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uninstall", action="store_true", help="Remove only marked package files, with backups")
    parser.add_argument("--component", choices=("roles", "skills", "all"), default="all",
                        help="With --uninstall: roles (including profiles), skills, or both (default: all)")
    parser.add_argument("--target", choices=(*TARGETS, "all"), default="all",
                        help="Provider to install, check or remove (default: all)")
    parser.add_argument("--codex-home", type=Path,
                        default=Path(os.environ.get("CODEX_HOME", str(Path.home() / ".codex"))))
    parser.add_argument("--claude-home", type=Path,
                        default=Path(os.environ.get("CLAUDE_CONFIG_DIR",
                                                    str(Path.home() / ".claude"))))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="Show changes without writing")
    mode.add_argument("--check", action="store_true", help="Exit 1 if installed files differ")
    parser.add_argument("--replace", action="store_true", help="Back up and replace unmanaged collisions")
    args = parser.parse_args()
    if args.uninstall and (args.check or args.replace):
        parser.error("--uninstall cannot be combined with --check or --replace")
    if args.component != "all" and not args.uninstall:
        parser.error("--component is only supported with --uninstall; deploy roles and skills together")
    targets = TARGETS if args.target == "all" else (args.target,)
    homes = {"codex": args.codex_home.expanduser().absolute(),
             "claude": args.claude_home.expanduser().absolute()}
    try:
        # Check original paths before collapsing '..', which could hide a symlink.
        for target in targets:
            home = homes[target]
            if any(path.is_symlink() for path in (home, *home.parents)):
                raise ValueError(f"Refusing symlink destination: {home}")
        homes = {target: Path(os.path.abspath(home)) for target, home in homes.items()}
        if (homes["codex"] == homes["claude"] and args.target != "all" and not args.check
                and not (args.uninstall and args.component == "roles")):
            parser.error("Provider homes share skill files; use --target all when changing skills, "
                         "or use separate homes")
        if args.uninstall:
            if args.component == "skills":
                warn_skill_dependencies(homes, targets)
            return deploy({}, retired=uninstall_paths(homes, targets, args.component),
                          dry_run=args.dry_run, uninstall=True)
        return deploy(resolve(render(targets=targets), homes),
                      dry_run=args.dry_run, retired=retired_paths(homes, targets),
                      check=args.check, replace=args.replace)
    except (OSError, ValueError) as error:
        print(f"Deployment failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
