#!/usr/bin/env python3
"""Generate Codex agent definitions and profiles from shared role instructions."""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by agentic-setup; edit source roles and redeploy.\n"
ROLES = ("lead", "scoper", "architect", "developer", "tester", "validator", "reviewer")


def render(root=ROOT):
    metadata = tomllib.loads((root / "codex/roles.toml").read_text())
    if set(metadata) != set(ROLES):
        raise ValueError(f"codex/roles.toml must define exactly: {', '.join(ROLES)}")
    common = (root / "roles/common.md").read_text().strip()
    outputs = {}
    for role in ROLES:
        settings = metadata[role]
        if set(settings) - {"description", "model", "model_reasoning_effort"}:
            raise ValueError(f"Unsupported metadata for {role}")
        if not settings.get("description") or not all(
            isinstance(value, str) for value in settings.values()
        ):
            raise ValueError(f"{role} metadata must contain nonempty description and string values")
        instructions = common + "\n\n" + (root / f"roles/{role}.md").read_text().strip() + "\n"
        if not common or not (root / f"roles/{role}.md").read_text().strip():
            raise ValueError(f"Empty instructions for {role}")
        runtime = {key: value for key, value in settings.items() if key != "description"}
        runtime["developer_instructions"] = instructions
        agent = {"name": role, "description": settings["description"], **runtime}
        for path, values in ((f"agents/{role}.toml", agent),
                             (f"agentic-{role}.config.toml", runtime)):
            # JSON strings with literal Unicode are also valid TOML basic strings.
            content = MARKER + "".join(
                f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
                for key, value in values.items()
            )
            assert tomllib.loads(content) == values
            outputs[path] = content
    return outputs


def deploy(destination, outputs, *, dry_run=False, check=False, replace=False):
    """Preflight all collisions; back up changed files and replace each atomically."""
    changes = []
    for relative, content in outputs.items():
        path = destination / relative
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
            raise ValueError(f"Refusing symlink destination: {path}")
        old = path.read_text() if path.exists() else None
        if old == content:
            continue
        if not check and old is not None and not old.startswith(MARKER) and not replace:
            raise ValueError(f"Unmanaged file: {path}. Review it, then use --replace to back it up.")
        changes.append((path, content, old))

    if check:
        for path, _, _ in changes:
            print(f"OUT OF DATE {path}")
        if not changes:
            print("Installed files match source.")
        return 1 if changes else 0

    for path, content, old in changes:
        print(f"{'Would write' if dry_run else 'Write'} {path}")
        if dry_run:
            if old is not None:
                print("  Would back up existing file.")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if old is not None:
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
            backup = path.with_name(f"{path.name}.bak-{stamp}")
            # Preserve exact bytes in backups, including original line endings.
            with backup.open("xb") as handle:
                handle.write(path.read_bytes())
            print(f"  Backup {backup}")
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent,
                                             delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(content)
            temporary.replace(path)
        finally:
            if temporary is not None and temporary.exists():
                temporary.unlink()
    if not changes:
        print("Already up to date.")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--codex-home", type=Path,
                        default=Path(os.environ.get("CODEX_HOME", str(Path.home() / ".codex"))))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="Show changes without writing")
    mode.add_argument("--check", action="store_true", help="Exit 1 if installed files differ")
    parser.add_argument("--replace", action="store_true", help="Back up and replace unmanaged collisions")
    args = parser.parse_args()
    try:
        return deploy(args.codex_home.expanduser().absolute(), render(), dry_run=args.dry_run,
                      check=args.check, replace=args.replace)
    except (OSError, ValueError) as error:
        print(f"Deployment failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
